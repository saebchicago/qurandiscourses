// build-changelog.mjs — one changelog registry, a page and a feed.
//
//   node scripts/build-changelog.mjs           # rewrite
//   node scripts/build-changelog.mjs --check   # exit 1 if stale
//
// data/changelog.json holds the entries (newest first, inner HTML
// verbatim). From it this writes:
//
//   changelog.html   the year/month/entry structure between
//                    static:changelog markers, each entry now carrying
//                    id="<entry id>" so a specific change is citable as
//                    /changelog#2026-08-<slug>, with a visible
//                    section-mark link like the claim permalinks
//   feed.xml         an Atom feed of the same entries, so releases and
//                    corrections are subscribable
//
// Entry dates are month-granular because that is what the changelog
// records; Atom timestamps use the first of the month, and the feed's
// own updated stamp is the newest entry's. Nothing reads the clock, so
// the output is deterministic. An entry id is permanent once shipped:
// feed readers and inbound links hold it. Zero dependencies.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { SITE } from "./lib/site.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const { entries } = JSON.parse(readFileSync(join(ROOT, "data/changelog.json"), "utf8"));

const MONTH_NUM = {
  January: "01", February: "02", March: "03", April: "04", May: "05",
  June: "06", July: "07", August: "08", September: "09", October: "10",
  November: "11", December: "12",
};

const failures = [];
const seen = new Set();
for (const e of entries) {
  if (!e.id || !/^\d{4}-\d{2}-[a-z0-9-]+$/.test(e.id)) failures.push(`bad id: ${e.id}`);
  if (seen.has(e.id)) failures.push(`duplicate id: ${e.id}`);
  seen.add(e.id);
  if (!MONTH_NUM[e.month]) failures.push(`${e.id}: unknown month ${e.month}`);
  if (!e.html || !e.html.trim()) failures.push(`${e.id}: empty html`);
}
if (failures.length) {
  console.error("build-changelog: registry invalid");
  for (const f of failures) console.error("  - " + f);
  process.exit(1);
}

// ── changelog.html region ────────────────────────────────────────────
const htmlParts = [];
let year = null;
let month = null;
let listOpen = false;
for (const e of entries) {
  if (e.year !== year) {
    if (listOpen) { htmlParts.push("          </ul>"); listOpen = false; }
    htmlParts.push(`          <h3>${e.year}</h3>`);
    year = e.year;
    month = null;
  }
  if (e.month !== month) {
    if (listOpen) { htmlParts.push("          </ul>"); listOpen = false; }
    htmlParts.push(`          <h4>${e.month}</h4>`);
    htmlParts.push("          <ul>");
    listOpen = true;
    month = e.month;
  }
  htmlParts.push(
    `            <li id="${e.id}">${e.html}<a class="claim-anchor" href="#${e.id}" aria-label="Link to this entry">&sect;</a></li>`,
  );
}
if (listOpen) htmlParts.push("          </ul>");
const region = htmlParts.join("\n");

// ── feed.xml ─────────────────────────────────────────────────────────
const esc = (v) =>
  String(v).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const dateOf = (e) => `${e.year}-${MONTH_NUM[e.month]}-01T00:00:00Z`;
const titleOf = (e) => {
  const strong = (e.html.match(/<strong>([\s\S]*?)<\/strong>/) || [, e.id])[1];
  return strong.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim().replace(/\.$/, "");
};

const feedEntries = entries
  .map(
    (e) => `  <entry>
    <title>${esc(titleOf(e))}</title>
    <id>${SITE}/changelog#${e.id}</id>
    <link href="${SITE}/changelog#${e.id}"/>
    <updated>${dateOf(e)}</updated>
    <content type="html">${esc(e.html.trim())}</content>
  </entry>`,
  )
  .join("\n");

const feed = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/build-changelog.mjs from data/changelog.json -->
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>Divine Discourses changelog</title>
  <subtitle>Every correction and material change, logged as a record of accountability.</subtitle>
  <id>${SITE}/changelog</id>
  <link href="${SITE}/changelog"/>
  <link rel="self" href="${SITE}/feed.xml"/>
  <updated>${dateOf(entries[0])}</updated>
  <author><name>Divine Discourses project</name></author>
${feedEntries}
</feed>
`;

// ── apply ────────────────────────────────────────────────────────────
const OPEN = "<!-- static:changelog -->";
const CLOSE = "          <!-- /static:changelog -->";
const abs = join(ROOT, "changelog.html");
const before = readFileSync(abs, "utf8");
const i = before.indexOf(OPEN);
const j = before.indexOf(CLOSE);
if (i === -1 || j === -1 || j < i)
  throw new Error("changelog.html: missing static:changelog markers");
const after = before.slice(0, i + OPEN.length) + "\n" + region + "\n" + before.slice(j);

let feedCurrent = null;
try {
  feedCurrent = readFileSync(join(ROOT, "feed.xml"), "utf8");
} catch {}

const stale = [];
if (after !== before) stale.push("changelog.html");
if (feedCurrent !== feed) stale.push("feed.xml");

if (CHECK) {
  if (stale.length) {
    console.error(
      `build-changelog --check: FAIL — stale: ${stale.join(", ")}\n  Run: node scripts/build-changelog.mjs`,
    );
    process.exit(1);
  }
  console.log(`build-changelog --check: OK (${entries.length} entries, page + feed current).`);
} else {
  if (after !== before) writeFileSync(abs, after);
  if (feedCurrent !== feed) writeFileSync(join(ROOT, "feed.xml"), feed);
  console.log(`build-changelog: ${entries.length} entries -> changelog.html + feed.xml (${stale.length} file(s) changed).`);
}
