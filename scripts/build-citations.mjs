// build-citations.mjs — one version, three citation surfaces.
//
//   node scripts/build-citations.mjs           # rewrite
//   node scripts/build-citations.mjs --check   # exit 1 if stale
//
// Reads data/version.json (the ONE place the version lives), then writes:
//
//   assets/version.js     window.QD_VERSION, so the footer "Cite" popover
//                         can name the version without a fetch
//   data/citations.bib    BibTeX for (1) the site, (2) each export table
//                         in data/exports/schema.json, (3) all sources in
//                         data/sources.json
//
// Every source must carry a `type` (book | paper | dataset | api); this
// generator throws on a missing or unknown one, which is what keeps the
// field from silently rotting as sources are added. Books become @book;
// everything else becomes @misc with the publisher line in howpublished,
// because the registry stores "City: Publisher, details" as one string
// and splitting it by guesswork would corrupt real citations. The file
// is UTF-8 (titles carry Arabic transliteration diacritics); biber reads
// it directly, classic bibtex users can transliterate.
//
// Deterministic: run twice, `git diff` is empty. Zero dependencies.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { SITE } from "./lib/site.mjs";
import { readJson } from "./lib/io.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

const { version, released } = readJson("data/version.json");
const sources = readJson("data/sources.json").sources;
const schema = readJson("data/exports/schema.json");

const TYPES = new Set(["book", "paper", "dataset", "api"]);
for (const s of sources) {
  if (!TYPES.has(s.type))
    throw new Error(
      `source "${s.id}" has type "${s.type}" — every source needs one of: ${[...TYPES].join(", ")}`,
    );
}

// BibTeX field escaping: preserve capitalization with braces, escape the
// characters BibTeX treats as syntax. Titles keep their Unicode.
const esc = (v) =>
  String(v).replace(/([&%$#_])/g, "\\$1").replace(/[{}]/g, "");
const field = (k, v) => (v ? `  ${k} = {${esc(v)}},\n` : "");

function entry(kind, key, fields) {
  let out = `@${kind}{${key},\n`;
  for (const [k, v] of fields) out += field(k, v);
  return out.replace(/,\n$/, "\n") + "}\n";
}

const year = released.slice(0, 4);
const blocks = [];

// 1. The site itself.
blocks.push(
  entry("misc", "divinediscourses", [
    ["title", "Divine Discourses"],
    ["author", "{Divine Discourses project}"],
    ["year", year],
    ["url", SITE],
    [
      "note",
      `Version ${version}, released ${released}. Site code MIT; bundled data keeps its own licenses (see ${SITE}/credits)`,
    ],
  ]),
);

// 2. One entry per export table, from the same schema.json that
// documents them, so a renamed table cannot leave a stale citation.
const tables = Object.keys(schema.tables).sort();
for (const name of tables) {
  const t = schema.tables[name];
  blocks.push(
    entry("misc", `divinediscourses-${name}`, [
      ["title", `Divine Discourses dataset: ${name}`],
      ["author", "{Divine Discourses project}"],
      ["year", year],
      ["url", `${SITE}/export`],
      ["howpublished", "CSV and JSON, with schema and data dictionary"],
      [
        "note",
        `${t.rowCount} rows. ${t.description} Version ${version}. Derived from the Leeds Quranic Arabic Corpus v0.4 (GPL)`,
      ],
    ]),
  );
}

// 3. The 25 cited sources, in registry order.
for (const s of sources) {
  const kind = s.type === "book" ? "book" : "misc";
  const fields = [
    ["title", s.name],
    ["author", s.author],
  ];
  if (kind === "book") {
    fields.push(["publisher", s.publisher], ["year", s.year], ["isbn", s.isbn]);
  } else {
    fields.push(["howpublished", s.publisher], ["year", s.year]);
  }
  fields.push(["url", s.url]);
  const noteBits = [];
  if (s.edition) noteBits.push(s.edition);
  if (s.license) noteBits.push(`License: ${s.license}`);
  if (s.accessed) noteBits.push(`Accessed ${s.accessed}`);
  fields.push(["note", noteBits.join(". ")]);
  blocks.push(entry(kind, s.id.replace(/[^a-zA-Z0-9.-]/g, "-"), fields));
}

const bib =
  `% citations.bib — GENERATED by scripts/build-citations.mjs; do not edit.\n` +
  `% The site, its ${tables.length} export tables, and its ${sources.length} cited sources.\n` +
  `% UTF-8 (use biber, or transliterate for classic bibtex).\n\n` +
  blocks.join("\n");

const versionJs =
  `// GENERATED by scripts/build-citations.mjs from data/version.json —\n` +
  `// do not edit. Read by assets/cite-page.js for the footer citation.\n` +
  `window.QD_VERSION = { version: "${version}", released: "${released}" };\n`;

const outputs = [
  ["data/citations.bib", bib],
  ["assets/version.js", versionJs],
];

let stale = [];
for (const [rel, text] of outputs) {
  const abs = join(ROOT, rel);
  let current = null;
  try {
    current = readFileSync(abs, "utf8");
  } catch {}
  if (current !== text) stale.push(rel);
  if (!CHECK) writeFileSync(abs, text);
}

if (CHECK) {
  if (stale.length) {
    console.error(
      `build-citations --check: FAIL — stale: ${stale.join(", ")}\n` +
        "  Run: node scripts/build-citations.mjs",
    );
    process.exit(1);
  }
  console.log(
    `build-citations --check: OK (v${version}: site + ${tables.length} tables + ${sources.length} sources).`,
  );
} else {
  console.log(
    `build-citations: wrote data/citations.bib and assets/version.js (v${version}, ${blocks.length} entries).`,
  );
}
