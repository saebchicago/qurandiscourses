// build-surahs-js.mjs — deterministic, zero-dependency generator for
// assets/surahs.js, the ONE canonical surah dataset every page shares.
//
// Rationale: three divergent surah lists used to exist (navigate.html's
// inline array, assets/surahs.js, read.html's SURAH_DISPLAY_NAMES) with
// different romanizations and one real data error (surah 55 marked
// Meccan against the Cairo 1924 convention both bundled datasets
// follow). This script merges the curated display names
// (data/surah-names.json — edit THAT file, never assets/surahs.js) with
// chronology.json (period, revelation order), surah-meta.json
// (classification), and surah-profiles.json (verse counts), asserting
// the sources agree before writing.
//
// Note on Arabic orthography: data/surah-names.json carries the common
// mushaf display forms (e.g. إبراهيم), which differ from
// surah-meta.json's API forms in a few hamza seats; the curated form
// wins for display and the divergence is deliberate.
//
// Run: node scripts/build-surahs-js.mjs
// Determinism check: run twice, `git diff` must be empty.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));

const names = read("data/surah-names.json");
const chronology = read("data/chronology.json");
const meta = read("data/surah-meta.json").surahs;
const profiles = read("data/surah-profiles.json").surahs;

const entries = [];
for (let id = 1; id <= 114; id++) {
  const k = String(id);
  const n = names[k];
  const c = chronology[k];
  const m = meta[k];
  const p = profiles[k];
  if (!n || !c || !m || !p) throw new Error(`Surah ${id}: missing in a source`);

  // The two independent sources must agree; fail loudly, never guess.
  if (c.revelationOrder !== m.revelationOrder)
    throw new Error(
      `Surah ${id}: revelationOrder mismatch chronology=${c.revelationOrder} meta=${m.revelationOrder}`,
    );
  const cls = m.classification === "makki" ? "m" : "d";
  const chronCls = c.period === "medinan" ? "d" : "m";
  if (cls !== chronCls)
    throw new Error(
      `Surah ${id}: classification mismatch meta=${m.classification} chronology period=${c.period}`,
    );
  if (!Array.isArray(n.aliases) || n.aliases.length === 0)
    throw new Error(`Surah ${id}: no Ask-box aliases in surah-names.json`);

  if (!n.en) throw new Error(`Surah ${id}: no English meaning in surah-names.json`);
  entries.push({
    id,
    translit: n.translit,
    ar: n.ar,
    en: n.en,
    verseCount: p.verseCount,
    cls,
    revOrder: c.revelationOrder,
    names: n.aliases,
  });
}

const body = entries
  .map(
    (e) =>
      `  { id: ${e.id}, translit: ${JSON.stringify(e.translit)}, ar: ${JSON.stringify(e.ar)}, en: ${JSON.stringify(e.en)}, verseCount: ${e.verseCount}, cls: ${JSON.stringify(e.cls)}, revOrder: ${e.revOrder}, names: ${JSON.stringify(e.names)} },`,
  )
  .join("\n");

const out = `// GENERATED by scripts/build-surahs-js.mjs — do not edit by hand.
// Edit data/surah-names.json (display names/aliases) and re-run the
// generator; other fields come from chronology.json, surah-meta.json,
// and surah-profiles.json.
//
// The one canonical surah dataset. Fields per entry:
//   id         1..114 (mushaf order)
//   translit   display transliteration (used by navigate.html, read.html)
//   ar         Arabic name, common mushaf orthography
//   en         English meaning (surah-names.json)
//   verseCount Cairo numbering, as tokenized by Leeds
//   cls        "m" Meccan | "d" Medinan (Cairo 1924 convention)
//   revOrder   Cairo 1924 revelation order
//   names      lowercase aliases for the Ask box fuzzy match
window.SURAHS = [
${body}
];
`;

writeFileSync(join(ROOT, "assets", "surahs.js"), out);
console.log(`Wrote assets/surahs.js with ${entries.length} surahs`);
