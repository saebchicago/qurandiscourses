// build-prayers.mjs — deterministic, zero-dependency generator for
// data/prayers/prayers.json, which backs /prayers.
//
// Two literal searches over the bundled Leeds morphology, no interpretation:
//
// 1. Vocative "rabbana" (Our Lord): the noun with lemma rab~, a first-person
//    plural pronoun suffix, and the accusative vowel on the ba. A noun in the
//    accusative that is not an address to God follows "inna" (35:34) or a verb
//    of seeing (25:21, "or see our Lord"). Those two contexts are excluded by
//    the previous word's lemma, and the exclusions are published beside the
//    counts. The nominative (rabbuna) and genitive (rabbina) forms are
//    statements about the Lord, not addresses to Him; they are counted apart.
// 2. Remembrance roots (sbH, Hmd, Dkr, gfr): token and verse counts straight
//    from the root field, with the lemmas that carry them.
//
// Speaker attribution is not computed here. Several vocative verses are
// spoken by people the text condemns; /prayers says so and links each verse.
//
// Run: node scripts/build-prayers.mjs [--check]

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "data", "prayers", "prayers.json");
const CHECK = process.argv.includes("--check");

const FOLD = /[ً-ْٰـ]/g;
const plain = (s) => s.replace(FOLD, "").replace(/ٱ/g, "ا");
const MARKS = /\u0631[\u064b-\u0652\u0670]*\u0628([\u064b-\u0652\u0670]*)/;
function vowelOnBa(ar) {
  const m = MARKS.exec(ar);
  const marks = m ? m[1] : "";
  if (marks.includes("َ")) return "accusative";
  if (marks.includes("ُ")) return "nominative";
  if (marks.includes("ِ")) return "genitive";
  return "none";
}
// Previous-word lemmas after which an accusative "rabbana" is not a vocative.
const NOT_VOCATIVE_AFTER = { "<in~": "after inna (subject)", "ra'aA": "object of a verb of seeing" };

const chron = JSON.parse(readFileSync(join(ROOT, "data", "chronology.json"), "utf8"));
const names = JSON.parse(readFileSync(join(ROOT, "data", "surah-names.json"), "utf8"));
const nameOf = (s) => (names[s] && names[s].translit) || "";

const REMEMBRANCE = ["sbH", "Hmd", "*kr", "gfr"];
const vocative = [];
const excluded = [];
const stateForms = { nominative: 0, genitive: 0 };
const remembrance = Object.fromEntries(REMEMBRANCE.map((r) => [r, { tokens: 0, verses: new Set(), lemmas: new Map() }]));
const versesPerPeriod = {};
let totalVerses = 0;

for (let s = 1; s <= 114; s++) {
  const morph = JSON.parse(readFileSync(join(ROOT, "data", "morphology", `${s}.json`), "utf8"));
  const period = chron[s].period;
  for (const [a, words] of Object.entries(morph)) {
    const ayah = Number(a);
    totalVerses++;
    versesPerPeriod[period] = (versesPerPeriod[period] || 0) + 1;
    words.forEach((w, i) => {
      if (REMEMBRANCE.includes(w.root)) {
        const r = remembrance[w.root];
        r.tokens++;
        r.verses.add(s * 1000 + ayah);
        r.lemmas.set(w.lemma, (r.lemmas.get(w.lemma) || 0) + 1);
      }
      if (w.lemma !== "rab~" || !/(نا|نآ)$/.test(plain(w.ar))) return;
      const kind = vowelOnBa(w.ar);
      if (kind === "nominative" || kind === "genitive") { stateForms[kind]++; return; }
      if (kind !== "accusative") return;
      const prev = i ? words[i - 1].lemma : "";
      if (NOT_VOCATIVE_AFTER[prev]) {
        excluded.push({ s, a: ayah, w: w.w, form: w.ar, reason: NOT_VOCATIVE_AFTER[prev] });
        return;
      }
      const next = words[i + 1];
      vocative.push({
        s, a: ayah, w: w.w, form: w.ar,
        nextLemma: next ? next.lemma : "", nextRoot: next ? next.root : "", nextAr: next ? next.ar : "",
        period,
      });
    });
  }
}

const byPeriod = {};
for (const v of vocative) byPeriod[v.period] = (byPeriod[v.period] || 0) + 1;
const nextCounts = new Map();
for (const v of vocative) {
  const k = v.nextLemma || "(end of verse)";
  nextCounts.set(k, (nextCounts.get(k) || 0) + 1);
}
const surahCounts = new Map();
for (const v of vocative) surahCounts.set(v.s, (surahCounts.get(v.s) || 0) + 1);

const out = {
  _comment:
    "GENERATED by scripts/build-prayers.mjs from data/morphology. Vocative 'rabbana' tokens (Our Lord, as an address) and remembrance-root counts. Speaker attribution is not computed.",
  method: {
    vocative:
      "Noun with lemma rab~ ending in the first-person plural suffix, with the accusative vowel on the ba, excluding tokens after inna or a verb of seeing. Nominative (rabbuna) and genitive (rabbina) forms are counted separately: they speak about the Lord, not to Him.",
    remembrance: "Token and verse counts for four roots, from the root field of the Leeds morphology.",
  },
  totals: { verses: totalVerses, versesPerPeriod },
  vocative: {
    tokens: vocative.length,
    verses: new Set(vocative.map((v) => v.s * 1000 + v.a)).size,
    surahs: surahCounts.size,
    nominativeForms: stateForms.nominative,
    genitiveForms: stateForms.genitive,
    excluded,
    byPeriod,
    surahCounts: [...surahCounts].sort((x, y) => y[1] - x[1] || x[0] - y[0]).map(([s, n]) => ({ s, name: nameOf(s), n })),
    nextWord: [...nextCounts].sort((x, y) => y[1] - x[1] || (x[0] < y[0] ? -1 : 1)).map(([lemma, n]) => ({ lemma, n })),
    entries: vocative,
  },
  remembrance: Object.fromEntries(
    REMEMBRANCE.map((r) => [
      r,
      {
        tokens: remembrance[r].tokens,
        verses: remembrance[r].verses.size,
        lemmas: [...remembrance[r].lemmas].sort((x, y) => y[1] - x[1] || (x[0] < y[0] ? -1 : 1)).map(([lemma, n]) => ({ lemma, n })),
      },
    ]),
  ),
};

const text = JSON.stringify(out, null, 1) + "\n";
if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
    console.error("build-prayers --check: FAIL — data/prayers/prayers.json is stale.\n  Run: node scripts/build-prayers.mjs");
    process.exit(1);
  }
  console.log(`build-prayers --check: OK (${vocative.length} vocative tokens in ${out.vocative.verses} verses).`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(
    `build-prayers: ${vocative.length} vocative tokens in ${out.vocative.verses} verses of ${surahCounts.size} surahs; ` +
      `${excluded.length} excluded; ${stateForms.nominative} nominative, ${stateForms.genitive} genitive.`,
  );
}
