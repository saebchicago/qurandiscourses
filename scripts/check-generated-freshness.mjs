// check-generated-freshness.mjs — the committed generated artifacts must
// be what the committed inputs actually produce.
//
//   node scripts/check-generated-freshness.mjs
//   node scripts/check-generated-freshness.mjs --only=build-numbers,build-themes
//
// WHY THIS EXISTS. 17 of this repo's 45 generators support `--check`, so
// CI notices when their output goes stale. The rest did not, and one of
// them drifted: data/coverage/report.json said 29 of 31 sources were
// reachable from a badge when the registry held 36 with 34 reachable,
// and coverage.html renders that number to readers. Nothing caught it
// for two releases. This checks the other 25 the only way that needs no
// per-generator work: it runs them and looks.
//
// WHY THEY HAD NO --check, WHICH IS NOT AN OVERSIGHT. Twelve of them
// stamp a `_computed` date into their output (scripts/lib/computed-date.mjs),
// so a byte-comparing check fails on every day but the one the artifact
// was written. Measured: rerunning every committed-input generator
// produced 9,863 differing files, of which 9,862 differed in the date
// stamp alone. So this compares content with the stamp removed, the same
// rule scripts/compute-coverage.mjs uses.
//
// WHY IT COPIES THE REPO. Generators resolve their output paths from
// import.meta.url and write in place. Running them against the working
// tree to see what they would produce is destructive — an earlier round
// did exactly that and rewrote ~10,000 files. Everything here happens in
// a temp directory, and the working tree is never written to. That is
// the property to preserve if this script is ever changed.
//
// A checker, not a generator: it writes nothing into the repo, so the
// determinism rule does not apply to it.

import { cpSync, mkdtempSync, rmSync, readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const ONLY = (args.find((a) => a.startsWith("--only=")) || "")
  .replace("--only=", "")
  .split(",")
  .filter(Boolean);

// Dependency order, read out of the generators' own inputs rather than
// guessed: root-analytics feeds roots-list and cooccurrence; cooccurrence
// feeds association; association feeds centrality and network-layout;
// centrality feeds dispersion; formulas feeds formula-summary,
// formulaic-density and structure; rhyme-map feeds structure; structure
// feeds structure-tests; surah-profiles feeds surahs-js and share-pages;
// build-exports reads nearly everything, so it runs last.
const ORDER = [
  "build-formulas",
  "build-rhyme-map",
  "build-symmetry-test",
  "build-discursive-pivots",
  "build-rhetorical-features",
  "build-juz",
  "build-numbers",
  "build-themes",
  "build-word-index",
  "build-root-refs-index",
  "build-root-analytics",
  "build-surah-profiles",
  "build-roots-list",
  "build-cooccurrence",
  "build-formula-summary",
  "build-formulaic-density",
  "build-structure",
  "build-structure-tests",
  "build-surahs-js",
  "compute-association-stats",
  "compute-centrality",
  "compute-network-layout",
  "compute-dispersion",
  "build-share-pages",
  "build-exports",
];

// Named and reported, never silently dropped: a run that skipped these
// without saying so would read as "all 45 checked".
const EXCLUDED = [
  ["build-og-images", "needs a browser"],
  ["build-surah-meta", "needs the network"],
  ["build-gloss", "manual utility, takes a raw-dump argument"],
];

// Only these trees are compared. Everything a generator writes lands in
// one of them; anything outside is reported as unattributed rather than
// ignored, so a generator that starts writing somewhere new shows up.
const WATCHED = ["data", "assets", "s"];

// ── Comparison, ignoring the date stamp ──────────────────────────────
const STAMP_LINE = /^.*\b\d{4}-\d{2}-\d{2}\b.*$/;

function comparable(text, path) {
  if (path.endsWith(".json")) {
    try {
      const parsed = JSON.parse(text);
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
        delete parsed._computed;
        delete parsed._generated;
      }
      return JSON.stringify(parsed);
    } catch {
      return text; // unparsable is a real difference, not something to smooth over
    }
  }
  // Text outputs. Only data/exports/DATA-DICTIONARY.md actually carries a
  // date; assets/surahs.js and assets/root-refs.js carry a "GENERATED by"
  // banner with no date and so compare byte-wise anyway. Dropping any
  // dated line is deliberately blunt: a checker that under-reports a real
  // difference is worse than one that ignores a line it did not need to.
  return text
    .split("\n")
    .filter((line) => !STAMP_LINE.test(line))
    .join("\n");
}

function sameContent(a, b, path) {
  if (a === b) return true;
  return comparable(a, path) === comparable(b, path);
}

// ── Filesystem helpers ───────────────────────────────────────────────
function walk(dir, since, out = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const full = join(dir, e.name);
    if (e.isDirectory()) walk(full, since, out);
    else if (e.isFile()) {
      try {
        if (statSync(full).mtimeMs >= since) out.push(full);
      } catch {
        /* vanished mid-walk */
      }
    }
  }
  return out;
}

function freshCopy() {
  const dir = mkdtempSync(join(tmpdir(), "qd-freshness-"));
  const dest = join(dir, "repo");
  cpSync(ROOT, dest, {
    recursive: true,
    filter: (src) => !src.includes(`${ROOT}/.git/`) && src !== `${ROOT}/.git`,
  });
  return { dir, dest };
}

// Runs one generator in `dest` and returns the repo-relative paths whose
// content differs from what is committed. Outputs are discovered by
// mtime rather than declared in a table here, so a generator that starts
// writing somewhere new is covered without this file being updated.
function runAndCompare(dest, name) {
  const started = Date.now();
  const r = spawnSync(process.execPath, [join("scripts", `${name}.mjs`)], {
    cwd: dest,
    encoding: "utf8",
    timeout: 900_000,
  });
  if (r.status !== 0) {
    return { error: (r.stderr || r.stdout || "no output").trim().split("\n").slice(-3).join(" | ") };
  }
  const written = [];
  for (const top of WATCHED) walk(join(dest, top), started, written);

  const drifted = [];
  for (const abs of written) {
    const rel = relative(dest, abs);
    const committed = join(ROOT, rel);
    if (!existsSync(committed)) {
      drifted.push({ rel, why: "not committed" });
      continue;
    }
    const a = readFileSync(committed, "utf8");
    const b = readFileSync(abs, "utf8");
    if (!sameContent(a, b, rel)) drifted.push({ rel, why: "content differs" });
  }
  return { wrote: written.length, drifted };
}

// ── Run ──────────────────────────────────────────────────────────────
const plan = ONLY.length ? ORDER.filter((g) => ONLY.includes(g)) : ORDER;
if (ONLY.length) {
  const unknown = ONLY.filter((g) => !ORDER.includes(g));
  if (unknown.length) {
    console.error(`check-generated-freshness: FAIL — unknown generator(s): ${unknown.join(", ")}`);
    process.exit(2);
  }
}

const { dir, dest } = freshCopy();
const results = [];
try {
  for (const name of plan) {
    const res = runAndCompare(dest, name);
    results.push({ name, ...res });
    if (res.error) console.log(`ERR   ${name} — ${res.error}`);
    else if (res.drifted.length) console.log(`DRIFT ${name} — ${res.drifted.length} of ${res.wrote} file(s)`);
    else console.log(`ok    ${name} — ${res.wrote} file(s) current`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}

const bad = results.filter((r) => r.error || r.drifted.length);

// Attribution pass. These generators feed each other, so once one has
// drifted every generator downstream of it is comparing against input
// that was just regenerated, and would be reported stale even if its own
// logic is fine. Re-run each suspect against its own pristine copy,
// where nothing upstream has been touched, so the report names the
// generator that actually needs re-running.
if (bad.length) {
  console.log("\nAttributing, one pristine copy per suspect:");
  for (const r of bad) {
    if (r.error) continue;
    const { dir: d2, dest: dest2 } = freshCopy();
    try {
      const solo = runAndCompare(dest2, r.name);
      r.solo = solo.error ? { error: solo.error } : { drifted: solo.drifted };
      const n = solo.drifted ? solo.drifted.length : 0;
      console.log(`  ${r.name}: ${solo.error ? "errored" : n ? `${n} file(s) genuinely stale` : "clean in isolation (downstream of another generator)"}`);
    } finally {
      rmSync(d2, { recursive: true, force: true });
    }
  }
}

console.log(
  `\nNot checked (${EXCLUDED.length}): ` + EXCLUDED.map(([n, why]) => `${n} (${why})`).join(", "),
);

const genuine = bad.filter((r) => r.error || (r.solo ? r.solo.error || (r.solo.drifted || []).length : true));
if (!genuine.length) {
  console.log(`check-generated-freshness: OK (${plan.length} generators, output matches what is committed).`);
  process.exit(0);
}

console.error("\ncheck-generated-freshness: FAIL");
for (const r of genuine) {
  if (r.error) {
    console.error(`  ${r.name} — did not run: ${r.error}`);
    continue;
  }
  const list = (r.solo && r.solo.drifted) || r.drifted;
  console.error(`  ${r.name} — ${list.length} file(s) stale. Run: node scripts/${r.name}.mjs`);
  for (const d of list.slice(0, 5)) console.error(`      ${d.rel} (${d.why})`);
  if (list.length > 5) console.error(`      ... and ${list.length - 5} more`);
}
console.error(
  `\n  ${genuine.length} generator(s) need re-running, in the order listed above.\n` +
    "  A stale artifact means the committed data is not what the committed\n" +
    "  inputs produce — re-run the generator, do not edit the artifact.",
);
process.exit(1);
