// build-root-refs-index.mjs — deterministic, zero-dependency generator
// for assets/root-refs.js, the small lookup that lets refs.js turn root
// mentions in page prose (e.g. "r-ḥ-m") into live popovers WITHOUT
// downloading the 1.9 MB roots-summary.json just to detect them.
//
// Two key spaces:
//   exact       lowercased rootLatin as written on the site, diacritics
//               kept ("ṣ-b-r") — always unambiguous
//   normalized  ask.js-style ASCII fold ("s-b-r") — indexed ONLY when
//               exactly one root normalizes to it (141 of 1,642 roots
//               collide after folding, e.g. ṣ-l-w vs s-l-w; wrapping an
//               ambiguous plain-ASCII token would guess, so refs.js
//               simply leaves those unwrapped unless written with
//               diacritics)
//
// Run: node scripts/build-root-refs-index.mjs
// Determinism check: run twice, `git diff` must be empty.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { safeKey } from "./lib/safe-key.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const summary = JSON.parse(
  readFileSync(join(ROOT, "data", "roots-summary.json"), "utf8"),
);

// Mirrors normalize() in assets/ask.js — keep in sync.
function normalize(s) {
  return s
    .toLowerCase()
    .trim()
    .replace(/[‘’'`]/g, "")
    .replace(/[ʿʾ]/g, "")
    .replace(/[āáà]/g, "a")
    .replace(/[īíì]/g, "i")
    .replace(/[ūúù]/g, "u")
    .replace(/[ḥ]/g, "h")
    .replace(/[ṣ]/g, "s")
    .replace(/[ḍ]/g, "d")
    .replace(/[ṭ]/g, "t")
    .replace(/[ẓ]/g, "z");
}

const exact = {};
const normCounts = {};
const normEntry = {};

for (const bw of Object.keys(summary).sort()) {
  const r = summary[bw];
  const entry = { k: safeKey(bw), a: r.rootArabic, l: r.rootLatin, bw };
  exact[r.rootLatin.toLowerCase()] = entry;
  const n = normalize(r.rootLatin);
  // Folding ʿ/' can produce malformed keys with empty segments — never
  // index those.
  if (/(^-|--|-$)/.test(n)) continue;
  normCounts[n] = (normCounts[n] || 0) + 1;
  normEntry[n] = entry;
}

const merged = { ...exact };
let ambiguous = 0;
for (const n of Object.keys(normEntry).sort()) {
  if (normCounts[n] > 1) {
    ambiguous++;
    continue; // plain-ASCII form is ambiguous: leave unwrapped
  }
  if (!merged[n]) merged[n] = normEntry[n];
}

const lines = Object.keys(merged)
  .sort()
  .map(
    (key) =>
      `  ${JSON.stringify(key)}: { k: ${JSON.stringify(merged[key].k)}, a: ${JSON.stringify(merged[key].a)}, l: ${JSON.stringify(merged[key].l)}, bw: ${JSON.stringify(merged[key].bw)} },`,
  );

const out = `// GENERATED by scripts/build-root-refs-index.mjs — do not edit.
// Lookup for assets/refs.js: token (lowercased, exact-diacritic or
// unambiguous ASCII-folded root Latin) -> { k: safeKey, a: Arabic,
// l: display Latin, bw: Buckwalter }. Ambiguous folded forms are
// deliberately absent — see the generator header.
window.ROOT_REFS = {
${lines.join("\n")}
};
`;

writeFileSync(join(ROOT, "assets", "root-refs.js"), out);
console.log(
  `root-refs: ${Object.keys(merged).length} keys (${Object.keys(exact).length} exact, ${ambiguous} ambiguous folded forms skipped)`,
);
