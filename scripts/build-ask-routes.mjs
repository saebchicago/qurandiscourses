// build-ask-routes.mjs — the Ask box's routing tables, as data.
//
//   node scripts/build-ask-routes.mjs           # rewrite
//   node scripts/build-ask-routes.mjs --check   # exit 1 if stale
//
// Two jobs:
//
// 1. Regenerate data/ask-routes.json's `glossary` table from
//    data/glossary.json's matchKeys, so a glossary rename can never
//    leave the Ask box routing to a dead anchor. The `themes` and
//    `pages` tables are hand-curated in the same file and pass through
//    untouched.
// 2. Emit assets/ask-routes.js (window.QD_ASK_ROUTES) so ask.js gets
//    the tables synchronously, with no fetch race on the page's most
//    used control — the same pattern as assets/version.js.
//
// check-ask.mjs (separate, in CI) validates every TARGET: theme slugs
// against themes.json, glossary anchors against glossary.json, page
// paths against files on disk. Deterministic; zero dependencies.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const routesPath = join(ROOT, "data/ask-routes.json");

const routes = JSON.parse(readFileSync(routesPath, "utf8"));
const glossaryTerms = JSON.parse(readFileSync(join(ROOT, "data/glossary.json"), "utf8")).terms;
// The juz table is derived, never hand-edited: "juz 5" must land on the
// verse juz 5 actually starts at, and data/juz.json is where that lives.
const juz = JSON.parse(readFileSync(join(ROOT, "data/juz.json"), "utf8")).juz.map((j) => ({
  juz: j.juz,
  startSurah: j.startSurah,
  startAyah: j.startAyah,
}));
routes.juz = juz;

// Rebuild the glossary table from the registry (sorted for stable diffs).
const glossary = {};
for (const t of glossaryTerms) {
  for (const k of [...t.matchKeys].sort()) glossary[k] = `/glossary#${t.id}`;
}
routes.glossary = Object.fromEntries(Object.entries(glossary).sort(([a], [b]) => (a < b ? -1 : 1)));

const routesJson = JSON.stringify(routes, null, 1) + "\n";

const js =
  `// GENERATED by scripts/build-ask-routes.mjs from data/ask-routes.json —\n` +
  `// do not edit. Read synchronously by assets/ask.js.\n` +
  `window.QD_ASK_ROUTES = ${JSON.stringify({
    themes: routes.themes,
    pages: routes.pages,
    glossary: routes.glossary,
    juz: routes.juz,
  })};\n`;

const outputs = [
  [routesPath, routesJson],
  [join(ROOT, "assets/ask-routes.js"), js],
];

const stale = [];
for (const [abs, text] of outputs) {
  let current = null;
  try {
    current = readFileSync(abs, "utf8");
  } catch {}
  if (current !== text) stale.push(abs.slice(ROOT.length + 1));
  if (!CHECK) writeFileSync(abs, text);
}

const counts = `${Object.keys(routes.themes).length} theme words, ${Object.keys(routes.pages).length} page words, ${Object.keys(routes.glossary).length} glossary keys`;
if (CHECK) {
  if (stale.length) {
    console.error(
      `build-ask-routes --check: FAIL — stale: ${stale.join(", ")}\n  Run: node scripts/build-ask-routes.mjs`,
    );
    process.exit(1);
  }
  console.log(`build-ask-routes --check: OK (${counts}).`);
} else {
  console.log(`build-ask-routes: wrote ask-routes.json + ask-routes.js (${counts}).`);
}
