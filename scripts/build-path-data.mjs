// build-path-data.mjs — the path ribbon's data, as synchronous JS.
//
//   node scripts/build-path-data.mjs           # rewrite
//   node scripts/build-path-data.mjs --check   # exit 1 if stale
//
// Emits assets/path-data.js (window.QD_PATHS) from data/paths.json so
// assets/path-ribbon.js can validate ?path=&step= and render the
// "Step N of M" ribbon with no fetch race — the same pattern as
// assets/version.js and assets/ask-routes.js. Only what the ribbon
// needs travels: title, per-step label, page and query, path minutes.
// The step html stays on paths.html, where it renders. query travels
// alongside page because the ribbon builds Previous/Next from these
// fields directly rather than parsing html at render time — omitting
// it here would silently strip every step's query params even though
// check-paths.mjs enforces the JSON side correctly.
//
// check-paths.mjs (separate, in CI) validates the registry itself:
// schema, minutes sums, href/page consistency, and that every page a
// step names actually loads the ribbon script. Deterministic; zero
// dependencies.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

const paths = JSON.parse(readFileSync(join(ROOT, "data/paths.json"), "utf8")).paths;

const table = {};
for (const p of paths) {
  table[p.id] = {
    title: p.title,
    minutes: p.minutes,
    steps: p.steps.map((s) => ({ label: s.label, page: s.page, query: s.query || "" })),
  };
}

const js =
  `// GENERATED by scripts/build-path-data.mjs from data/paths.json —\n` +
  `// do not edit. Read synchronously by assets/path-ribbon.js.\n` +
  `window.QD_PATHS = ${JSON.stringify(table)};\n`;

const abs = join(ROOT, "assets/path-data.js");
let current = null;
try {
  current = readFileSync(abs, "utf8");
} catch {
  current = null;
}

if (CHECK) {
  if (current !== js) {
    console.error("build-path-data --check: FAIL");
    console.error("  - assets/path-data.js is stale. Run: node scripts/build-path-data.mjs");
    process.exit(1);
  }
  console.log(`build-path-data --check: OK (${paths.length} paths mirrored)`);
} else {
  if (current !== js) writeFileSync(abs, js);
  console.log(
    `build-path-data: ${paths.length} paths mirrored to assets/path-data.js${current === js ? " (no change)" : ""}.`,
  );
}
