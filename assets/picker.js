/* Click-first surah, juz, and verse-range selection.

   The site's selection controls all assumed typing: a surah number in
   one box, a verse number in another. This module makes every surah,
   every juz position, and every verse range reachable by tapping, for
   readers who do not want to type. The typed forms stay exactly where
   they were on each page: they are the no-JS baseline, and this
   enhances them rather than replacing them.

   Data comes from window.SURAHS (assets/surahs.js, the one canonical
   surah dataset: id, translit, ar, en, verseCount, cls, revOrder) and
   data/juz.json (generated by scripts/build-juz.mjs from the cited
   Tanzil boundaries). Nothing new is fetched or bundled.

   Public API:
     qdPicker.open({surah, from, to, trigger, rangeMode, onSelect})
       Opens the dialog. onSelect({surah, from, to}) fires on confirm.
       rangeMode "range" (default) shows the From/To step; "surah"
       skips it and confirms on surah tap.
     qdPicker.openList({items, groups, filters, selected, multi, title,
                         searchPlaceholder, confirmLabel, minSelected,
                         trigger, onConfirm})
       A second, generic dialog mode sharing this module's overlay,
       search box, filter chips, and focus trap, but over an arbitrary
       item list (checkboxes, not surah rows) instead of surahs. Built
       for assets/trans-picker.js; any future host with its own list to
       pick from can reuse it the same way. onConfirm(ids) fires once,
       on confirm, with every checked item's id -- nothing commits
       per-checkbox.
     qdRange.create(container, {surah, from, to, onChange})
       The From/To control on its own, for hosts that want it inline.
       Returns {set(surah, from, to), get(), destroy()}.

   Recents live in window.qdState (the single qd_state object every
   other preference uses), never in a key of their own. */
(function () {
  "use strict";

  var esc = function (v) {
    return window.qdEsc ? window.qdEsc(v) : String(v == null ? "" : v);
  };

  // Matches navigate.html's published "Short (under 30)" threshold. Two
  // different definitions of Short on one site would be worse than
  // matching, and the criterion is stated on the chip either way.
  var SHORT_MAX = 29;

  function surahs() {
    return window.SURAHS || [];
  }
  function surahById(id) {
    return surahs().find(function (s) {
      return s.id === Number(id);
    });
  }
  function verseCount(id) {
    var s = surahById(id);
    return s ? s.verseCount : 1;
  }

  // ── Recents, stored inside qd_state ───────────────────────────────
  function recents() {
    var st = window.qdState;
    if (!st || !st.progress || !Array.isArray(st.progress.recentSurahs)) return [];
    return st.progress.recentSurahs.filter(function (n) {
      return n >= 1 && n <= 114;
    });
  }
  function pushRecent(id) {
    var st = window.qdState;
    if (!st) return;
    if (!st.progress) st.progress = {};
    var list = Array.isArray(st.progress.recentSurahs)
      ? st.progress.recentSurahs.slice()
      : [];
    list = list.filter(function (n) {
      return n !== Number(id);
    });
    list.unshift(Number(id));
    st.progress.recentSurahs = list.slice(0, 5);
    if (window.qdSaveState) window.qdSaveState();
  }

  // ── Range clamping ────────────────────────────────────────────────
  // The one place bounds are enforced. Every input path (steppers,
  // typing, surah switch, URL hydration) goes through this, so an
  // inverted or out-of-bounds range cannot be produced.
  function clampRange(surah, from, to, moved) {
    var max = verseCount(surah);
    var f = parseInt(from, 10);
    var t = parseInt(to, 10);
    if (!(f >= 1)) f = 1;
    if (!(t >= 1)) t = max;
    if (f > max) f = max;
    if (t > max) t = max;
    if (f > t) {
      // Push the box the reader did NOT just touch, so their edit stands.
      if (moved === "to") f = t;
      else t = f;
    }
    return { from: f, to: t };
  }

  function refLabel(surah, from, to) {
    return surah + ":" + (from === to ? from : from + "-" + to);
  }

  // ── Range control ─────────────────────────────────────────────────
  // Instance ids, not fixed ones: Read carries an inline range while
  // the dialog builds a second, and duplicate ids would silently break
  // the label-to-input association for both.
  var rangeSeq = 0;

  function createRange(container, opts) {
    opts = opts || {};
    var surah = Number(opts.surah) || 1;
    var r = clampRange(surah, opts.from, opts.to);
    var uid = "qdRange" + ++rangeSeq;

    container.innerHTML =
      '<div class="qd-range">' +
      '<div class="qd-range-box">' +
      '<label class="qd-range-label" for="' + uid + 'From">From verse</label>' +
      '<div class="qd-stepper">' +
      '<button type="button" class="qd-step" data-step="from-down" aria-label="Decrease first verse">&minus;</button>' +
      '<input type="number" id="' + uid + 'From" class="qd-range-input" inputmode="numeric" min="1" />' +
      '<button type="button" class="qd-step" data-step="from-up" aria-label="Increase first verse">+</button>' +
      "</div></div>" +
      '<div class="qd-range-box">' +
      '<label class="qd-range-label" for="' + uid + 'To">To verse</label>' +
      '<div class="qd-stepper">' +
      '<button type="button" class="qd-step" data-step="to-down" aria-label="Decrease last verse">&minus;</button>' +
      '<input type="number" id="' + uid + 'To" class="qd-range-input" inputmode="numeric" min="1" />' +
      '<button type="button" class="qd-step" data-step="to-up" aria-label="Increase last verse">+</button>' +
      '<button type="button" class="qd-to-end" data-step="to-end">to end</button>' +
      "</div></div>" +
      '<p class="qd-range-readout" role="status" aria-live="polite"></p>' +
      "</div>";

    var fromEl = container.querySelector("#" + uid + "From");
    var toEl = container.querySelector("#" + uid + "To");
    var readout = container.querySelector(".qd-range-readout");

    function paint(moved) {
      var c = clampRange(surah, fromEl.value, toEl.value, moved);
      r = c;
      fromEl.max = verseCount(surah);
      toEl.max = verseCount(surah);
      fromEl.value = c.from;
      toEl.value = c.to;
      readout.textContent = refLabel(surah, c.from, c.to);
      if (opts.onChange) opts.onChange({ surah: surah, from: c.from, to: c.to });
    }

    // Bound to the .qd-range element this function just created, NOT to
    // `container`, which it does not own and only ever overwrites the
    // innerHTML of. Binding to the container stacked one handler per
    // call: the surah dialog's "Choose a different surah" path clears
    // rangeHost.innerHTML and calls createRange again, so every
    // round-trip added another listener closed over the PREVIOUS surah's
    // inputs, and each stepper click then ran paint() once per stale
    // handler. Binding to the replaced element makes the old handler
    // garbage along with the markup it belonged to.
    var rangeRoot = container.querySelector(".qd-range");
    rangeRoot.addEventListener("click", function (e) {
      var btn = e.target.closest && e.target.closest(".qd-step");
      if (!btn) return;
      var step = btn.getAttribute("data-step");
      if (step === "from-down") fromEl.value = Number(fromEl.value) - 1;
      if (step === "from-up") fromEl.value = Number(fromEl.value) + 1;
      if (step === "to-down") toEl.value = Number(toEl.value) - 1;
      if (step === "to-up") toEl.value = Number(toEl.value) + 1;
      // "to end" is the reason this control exists: a reader who does
      // not know where the surah stops should not have to.
      if (step === "to-end") toEl.value = verseCount(surah);
      paint(step.indexOf("to-") === 0 ? "to" : "from");
    });
    fromEl.addEventListener("input", function () {
      paint("from");
    });
    toEl.addEventListener("input", function () {
      paint("to");
    });
    // Typing an empty box should not commit a bogus value mid-edit; the
    // clamp runs again on blur to settle it.
    fromEl.addEventListener("blur", function () {
      paint("from");
    });
    toEl.addEventListener("blur", function () {
      paint("to");
    });

    fromEl.value = r.from;
    toEl.value = r.to;
    paint();

    return {
      set: function (s, f, t) {
        surah = Number(s) || surah;
        var c = clampRange(surah, f, t);
        fromEl.value = c.from;
        toEl.value = c.to;
        paint();
      },
      get: function () {
        return { surah: surah, from: r.from, to: r.to };
      },
    };
  }

  // ── Dialog ────────────────────────────────────────────────────────
  var openState = null;

  function surahRowHtml(s) {
    return (
      '<button type="button" class="qd-surah" data-surah="' + s.id + '">' +
      '<span class="qd-surah-num">' + s.id + "</span>" +
      '<span class="qd-surah-main">' +
      '<span class="ar notranslate qd-surah-ar" translate="no" lang="ar" dir="rtl">' +
      esc(s.ar) + "</span>" +
      '<span class="qd-surah-translit">' + esc(s.translit) + "</span>" +
      '<span class="qd-surah-en">' + esc(s.en) + "</span>" +
      "</span>" +
      '<span class="qd-surah-count">' + s.verseCount +
      (s.verseCount === 1 ? " verse" : " verses") + "</span>" +
      "</button>"
    );
  }

  function close(restoreFocus) {
    if (!openState) return;
    var trigger = openState.trigger;
    openState.overlay.remove();
    document.removeEventListener("keydown", openState.onKey, true);
    openState = null;
    if (restoreFocus !== false && trigger && trigger.focus) trigger.focus();
  }

  // Focus restore for the confirm path, where the act of confirming can
  // destroy the very element focus should return to (Read re-renders its
  // whole verse container on qd:translations-changed). Focus the trigger
  // if it is still in the document; if a re-render detaches it within a
  // short window, re-target the equivalent live element instead of
  // leaving the reader stranded on <body> at the top of the page.
  function restoreFocusAfterConfirm(trigger) {
    if (!trigger || !trigger.focus) return;
    var selector = trigger.id
      ? "#" + trigger.id
      : trigger.classList && trigger.classList.length
        ? "." + trigger.classList[0]
        : null;
    if (trigger.isConnected) trigger.focus();
    if (!selector) return;
    var settled = false;
    var obs = new MutationObserver(function () {
      if (settled) return;
      if (trigger.isConnected) return;
      var next = document.querySelector(selector);
      if (!next) return;
      settled = true;
      obs.disconnect();
      next.focus();
    });
    obs.observe(document.body, { childList: true, subtree: true });
    // Bounded: a confirm that triggers no re-render must not leave an
    // observer running for the life of the page.
    setTimeout(function () {
      settled = true;
      obs.disconnect();
    }, 2000);
  }

  // Escape-closes, Tab-wraps within dialog. Shared by open() and
  // openList() so there is exactly one focus-trap implementation, not
  // two dialogs quietly drifting apart.
  function makeKeyHandler(dialog) {
    function focusable() {
      return Array.prototype.slice
        .call(dialog.querySelectorAll("button, input, [href], select"))
        .filter(function (el) {
          return el.offsetParent !== null && !el.disabled;
        });
    }
    return function (e) {
      if (!openState) return;
      if (e.key === "Escape") {
        e.preventDefault();
        // stopPropagation matters as much as preventDefault here. This
        // handler runs on document in the CAPTURE phase, so without it
        // every bubble-phase Escape handler on the page still fires:
        // app.js closes the settings panel and moves focus to the gear
        // button, notebook.js closes its panel. Opening the picker from
        // the gear panel and pressing Escape therefore tore down two
        // layers at once and overrode the picker's own focus restore.
        // The modal this dialog replaced called stopPropagation for
        // exactly this reason.
        e.stopPropagation();
        close();
        return;
      }
      if (e.key !== "Tab") return;
      var els = focusable();
      if (!els.length) return;
      var first = els[0];
      var last = els[els.length - 1];
      // Clicking a non-focusable part of the dialog (the heading, a group
      // label, body padding) leaves activeElement on <body>, which is
      // neither first nor last — so without this branch Tab walked out of
      // the dialog into the page behind it, with no visible focus ring and
      // no way back. Pull focus back to the top of the dialog instead.
      if (!dialog.contains(document.activeElement)) {
        e.preventDefault();
        (e.shiftKey ? last : first).focus();
        return;
      }
      if (e.shiftKey && document.activeElement === first) {
        e.preventDefault();
        last.focus();
      } else if (!e.shiftKey && document.activeElement === last) {
        e.preventDefault();
        first.focus();
      }
    };
  }

  function open(opts) {
    opts = opts || {};
    if (openState) close(false);

    var surah = Number(opts.surah) || 1;
    var rangeMode = opts.rangeMode === "surah" ? "surah" : "range";
    var pending = { surah: surah, from: opts.from, to: opts.to };

    var overlay = document.createElement("div");
    overlay.className = "qd-picker-overlay";
    overlay.innerHTML =
      '<div class="qd-picker" role="dialog" aria-modal="true" aria-labelledby="qdPickerTitle">' +
      '<div class="qd-picker-head">' +
      '<h2 id="qdPickerTitle">Choose a surah</h2>' +
      '<button type="button" class="qd-picker-close" aria-label="Close">&times;</button>' +
      "</div>" +
      '<div class="qd-picker-filters" role="group" aria-label="Filter surahs">' +
      '<button type="button" class="qd-chip is-on" data-filter="all">All</button>' +
      '<button type="button" class="qd-chip" data-filter="short">Short (under 30 verses)</button>' +
      '<button type="button" class="qd-chip" data-filter="m">Meccan</button>' +
      '<button type="button" class="qd-chip" data-filter="d">Medinan</button>' +
      '<button type="button" class="qd-chip" data-filter="juz">By juz</button>' +
      "</div>" +
      '<label class="qd-picker-search"><span>Filter by name (optional)</span>' +
      '<input type="text" class="qd-picker-q" autocomplete="off" spellcheck="false" placeholder="Type to narrow the list" /></label>' +
      '<div class="qd-picker-body"></div>' +
      '<div class="qd-picker-foot" hidden>' +
      '<div class="qd-picker-range"></div>' +
      '<button type="button" class="button qd-picker-confirm">Use this passage</button>' +
      "</div>" +
      "</div>";
    document.body.appendChild(overlay);

    var dialog = overlay.querySelector(".qd-picker");
    var body = overlay.querySelector(".qd-picker-body");
    var foot = overlay.querySelector(".qd-picker-foot");
    var rangeHost = overlay.querySelector(".qd-picker-range");
    var qInput = overlay.querySelector(".qd-picker-q");
    var rangeCtl = null;

    function renderList(filter, q) {
      var list = surahs().slice();
      if (filter === "short")
        list = list.filter(function (s) {
          return s.verseCount <= SHORT_MAX;
        });
      if (filter === "m" || filter === "d")
        list = list.filter(function (s) {
          return s.cls === filter;
        });
      if (q) {
        var needle = q.toLowerCase();
        list = list.filter(function (s) {
          return (
            String(s.id) === needle ||
            s.translit.toLowerCase().indexOf(needle) !== -1 ||
            s.en.toLowerCase().indexOf(needle) !== -1 ||
            s.ar.indexOf(q) !== -1 ||
            (s.names || []).some(function (n) {
              return n.indexOf(needle) !== -1;
            })
          );
        });
      }

      var html = "";
      var rec = recents();
      if (rec.length && filter === "all" && !q) {
        html +=
          '<h3 class="qd-picker-group">Recent</h3><div class="qd-surah-list">' +
          rec
            .map(function (id) {
              var s = surahById(id);
              return s ? surahRowHtml(s) : "";
            })
            .join("") +
          "</div>";
        html += '<h3 class="qd-picker-group">All surahs</h3>';
      }
      html +=
        '<div class="qd-surah-list">' +
        (list.length
          ? list.map(surahRowHtml).join("")
          : '<p class="qd-picker-empty">No surah matches that.</p>') +
        "</div>";
      body.innerHTML = html;
    }

    function renderJuz() {
      body.innerHTML = '<p class="qd-picker-empty">Loading juz divisions.</p>';
      fetch("data/juz.json")
        .then(function (r) {
          if (!r.ok) throw new Error("HTTP " + r.status);
          return r.json();
        })
        .then(function (d) {
          body.innerHTML =
            '<h3 class="qd-picker-group">Juz 1 to 30</h3>' +
            '<div class="qd-juz-grid">' +
            d.juz
              .map(function (j) {
                return (
                  '<button type="button" class="qd-juz" data-juz="' + j.juz + '">' +
                  '<span class="qd-juz-n">' + j.juz + "</span>" +
                  '<span class="qd-juz-span">' +
                  j.startSurah + ":" + j.startAyah + " to " +
                  j.endSurah + ":" + j.endAyah +
                  "</span></button>"
                );
              })
              .join("") +
            "</div>";
          body.__juz = d.juz;
        })
        .catch(function () {
          body.innerHTML =
            '<p class="qd-picker-empty">Could not load the juz divisions. Pick a surah from the list instead.</p>';
        });
    }

    // A juz can span several surahs; decompose it into per-surah ranges
    // from the boundaries in juz.json plus each surah's verse count, so
    // no second data file is needed.
    function juzParts(j) {
      var parts = [];
      for (var s = j.startSurah; s <= j.endSurah; s++) {
        var from = s === j.startSurah ? j.startAyah : 1;
        var to = s === j.endSurah ? j.endAyah : verseCount(s);
        parts.push({ surah: s, from: from, to: to });
      }
      return parts;
    }

    function showRangeStep(id) {
      pending.surah = id;
      var s = surahById(id);
      dialog.querySelector("#qdPickerTitle").textContent =
        "Verses in " + (s ? s.translit : "surah " + id);
      foot.hidden = false;
      body.innerHTML =
        '<p class="qd-picker-chosen">Surah ' + id + ", " +
        esc(s ? s.translit : "") + ", " + verseCount(id) +
        (verseCount(id) === 1 ? " verse." : " verses.") +
        ' <button type="button" class="qd-picker-back">Choose a different surah</button></p>';
      rangeCtl = createRange(rangeHost, {
        surah: id,
        from: pending.from,
        to: pending.to,
      });
      var conf = overlay.querySelector(".qd-picker-confirm");
      if (conf) conf.focus();
    }

    function confirm() {
      var val = rangeCtl
        ? rangeCtl.get()
        : { surah: pending.surah, from: 1, to: verseCount(pending.surah) };
      pushRecent(val.surah);
      close();
      if (opts.onSelect) opts.onSelect(val);
    }

    overlay.addEventListener("click", function (e) {
      if (e.target === overlay) return close();

      var chip = e.target.closest && e.target.closest(".qd-chip");
      if (chip) {
        overlay.querySelectorAll(".qd-chip").forEach(function (c) {
          c.classList.toggle("is-on", c === chip);
        });
        var f = chip.getAttribute("data-filter");
        qInput.value = "";
        if (f === "juz") renderJuz();
        else renderList(f, "");
        return;
      }

      var juzBtn = e.target.closest && e.target.closest(".qd-juz");
      if (juzBtn) {
        var j = (body.__juz || []).find(function (x) {
          return String(x.juz) === juzBtn.getAttribute("data-juz");
        });
        if (!j) return;
        var parts = juzParts(j);
        body.innerHTML =
          '<h3 class="qd-picker-group">Juz ' + j.juz + "</h3>" +
          // The whole juz in one go, above the per-surah breakdown:
          // juzParts() has always computed the full span and the UI
          // only ever let a reader keep one part of it.
          '<p class="qd-juz-whole"><a class="button btn-primary" href="/read?j=' +
          j.juz + '">Read all of juz ' + j.juz + "</a></p>" +
          '<div class="qd-surah-list">' +
          parts
            .map(function (p) {
              var s = surahById(p.surah);
              return (
                '<button type="button" class="qd-surah" data-surah="' + p.surah +
                '" data-from="' + p.from + '" data-to="' + p.to + '">' +
                '<span class="qd-surah-num">' + p.surah + "</span>" +
                '<span class="qd-surah-main">' +
                '<span class="ar notranslate qd-surah-ar" translate="no" lang="ar" dir="rtl">' +
                esc(s ? s.ar : "") + "</span>" +
                '<span class="qd-surah-translit">' + esc(s ? s.translit : "") + "</span>" +
                "</span>" +
                '<span class="qd-surah-count">' + refLabel(p.surah, p.from, p.to) + "</span>" +
                "</button>"
              );
            })
            .join("") +
          "</div>";
        return;
      }

      var row = e.target.closest && e.target.closest(".qd-surah");
      if (row) {
        var id = Number(row.getAttribute("data-surah"));
        var hasRange = row.hasAttribute("data-from");
        pending.from = hasRange ? Number(row.getAttribute("data-from")) : 1;
        pending.to = hasRange ? Number(row.getAttribute("data-to")) : verseCount(id);
        if (rangeMode === "surah") {
          pending.surah = id;
          pushRecent(id);
          close();
          if (opts.onSelect)
            opts.onSelect({ surah: id, from: pending.from, to: pending.to });
          return;
        }
        showRangeStep(id);
        return;
      }

      if (e.target.closest && e.target.closest(".qd-picker-back")) {
        foot.hidden = true;
        rangeCtl = null;
        rangeHost.innerHTML = "";
        dialog.querySelector("#qdPickerTitle").textContent = "Choose a surah";
        renderList("all", "");
        return;
      }

      if (e.target.closest && e.target.closest(".qd-picker-confirm")) confirm();
      if (e.target.closest && e.target.closest(".qd-picker-close")) close();
    });

    qInput.addEventListener("input", function () {
      var on = overlay.querySelector(".qd-chip.is-on");
      var f = on ? on.getAttribute("data-filter") : "all";
      if (f === "juz") return;
      renderList(f, qInput.value.trim());
    });

    var onKey = makeKeyHandler(dialog);
    document.addEventListener("keydown", onKey, true);

    openState = { overlay: overlay, trigger: opts.trigger || null, onKey: onKey };
    renderList("all", "");
    var closeBtn = overlay.querySelector(".qd-picker-close");
    if (closeBtn) closeBtn.focus();
  }

  // ── Generic multi-select list dialog ────────────────────────────────
  // Same overlay/search/filter-chip/focus-trap chrome as open(), over an
  // arbitrary item list instead of surahs. items: [{id, primary,
  // secondary, group, meta, searchText}]. groups (optional): [{key,
  // label}] in display order; ungrouped items render in one flat list
  // after named groups. filters (optional): [{key, label, test(item)}].
  function openList(opts) {
    opts = opts || {};
    if (openState) close(false);

    var multi = opts.multi !== false;
    var items = opts.items || [];
    var groups = opts.groups || [];
    var filters = opts.filters || [];
    var selected = {};
    (opts.selected || []).forEach(function (id) {
      selected[id] = true;
    });
    var confirmLabel = opts.confirmLabel || "Apply";
    var title = opts.title || "Choose";
    var searchPlaceholder = opts.searchPlaceholder || "Type to filter";
    var emptyText = opts.emptyText || "Nothing matches that.";
    var minSelected = opts.minSelected != null ? opts.minSelected : multi ? 1 : 0;

    var overlay = document.createElement("div");
    overlay.className = "qd-picker-overlay";
    overlay.innerHTML =
      '<div class="qd-picker qd-picker-list" role="dialog" aria-modal="true" aria-labelledby="qdPickerTitle">' +
      '<div class="qd-picker-head">' +
      '<h2 id="qdPickerTitle">' + esc(title) + "</h2>" +
      '<button type="button" class="qd-picker-close" aria-label="Close">&times;</button>' +
      "</div>" +
      (filters.length
        ? '<div class="qd-picker-filters" role="group" aria-label="Filter">' +
          '<button type="button" class="qd-chip is-on" data-filter="all">All</button>' +
          filters
            .map(function (f) {
              return '<button type="button" class="qd-chip" data-filter="' + esc(f.key) + '">' + esc(f.label) + "</button>";
            })
            .join("") +
          "</div>"
        : "") +
      '<label class="qd-picker-search"><span>Search</span>' +
      '<input type="text" class="qd-picker-q" autocomplete="off" spellcheck="false" placeholder="' + esc(searchPlaceholder) + '" /></label>' +
      '<div class="qd-picker-body"></div>' +
      '<div class="qd-picker-foot">' +
      '<div class="qd-picker-count" role="status" aria-live="polite"></div>' +
      '<button type="button" class="button qd-picker-confirm">' + esc(confirmLabel) + "</button>" +
      "</div>" +
      "</div>";
    document.body.appendChild(overlay);

    var dialog = overlay.querySelector(".qd-picker");
    var body = overlay.querySelector(".qd-picker-body");
    var qInput = overlay.querySelector(".qd-picker-q");
    var countEl = overlay.querySelector(".qd-picker-count");
    var confirmBtn = overlay.querySelector(".qd-picker-confirm");

    function selectedCount() {
      var n = 0;
      for (var k in selected) if (selected[k]) n++;
      return n;
    }

    function paintFoot() {
      var n = selectedCount();
      countEl.textContent = n + " selected";
      confirmBtn.disabled = n < minSelected;
    }

    function itemRowHtml(it) {
      return (
        '<label class="qd-list-row">' +
        '<input type="checkbox" data-item="' + esc(it.id) + '"' +
        (selected[it.id] ? " checked" : "") + ">" +
        '<span class="qd-list-main">' +
        '<span class="qd-list-primary">' + esc(it.primary) + "</span>" +
        (it.secondary ? '<span class="qd-list-secondary">' + esc(it.secondary) + "</span>" : "") +
        "</span>" +
        (it.meta ? '<span class="qd-list-meta">' + esc(it.meta) + "</span>" : "") +
        "</label>"
      );
    }

    function renderList(filterKey, q) {
      var list = items.slice();
      if (filterKey && filterKey !== "all") {
        var filt = filters.filter(function (f) {
          return f.key === filterKey;
        })[0];
        if (filt && filt.test) list = list.filter(filt.test);
      }
      if (q) {
        var needle = q.toLowerCase();
        list = list.filter(function (it) {
          return (it.searchText || it.primary + " " + (it.secondary || "")).toLowerCase().indexOf(needle) !== -1;
        });
      }

      var html = "";
      var showSelectedGroup = !q && (!filterKey || filterKey === "all");
      var rendered = {};
      if (showSelectedGroup) {
        var selItems = list.filter(function (it) {
          return selected[it.id];
        });
        if (selItems.length) {
          html += '<h3 class="qd-picker-group">Selected</h3><div class="qd-list">' + selItems.map(itemRowHtml).join("") + "</div>";
          selItems.forEach(function (it) {
            rendered[it.id] = true;
          });
        }
      }

      if (groups.length) {
        groups.forEach(function (g) {
          var groupItems = list.filter(function (it) {
            return it.group === g.key && !rendered[it.id];
          });
          if (!groupItems.length) return;
          html +=
            '<h3 class="qd-picker-group">' + esc(g.label) +
            ' <span class="qd-picker-group-count">(' + groupItems.length + ")</span></h3>" +
            '<div class="qd-list">' + groupItems.map(itemRowHtml).join("") + "</div>";
        });
        var ungrouped = list.filter(function (it) {
          return !rendered[it.id] && !groups.some(function (g) {
            return g.key === it.group;
          });
        });
        if (ungrouped.length) {
          html += '<div class="qd-list">' + ungrouped.map(itemRowHtml).join("") + "</div>";
        }
      } else {
        var flat = list.filter(function (it) {
          return !rendered[it.id];
        });
        if (flat.length) html += '<div class="qd-list">' + flat.map(itemRowHtml).join("") + "</div>";
      }

      if (!list.length) html = '<p class="qd-picker-empty">' + esc(emptyText) + "</p>";
      body.innerHTML = html;
    }

    overlay.addEventListener("click", function (e) {
      if (e.target === overlay) return close();

      var chip = e.target.closest && e.target.closest(".qd-chip");
      if (chip) {
        overlay.querySelectorAll(".qd-chip").forEach(function (c) {
          c.classList.toggle("is-on", c === chip);
        });
        qInput.value = "";
        renderList(chip.getAttribute("data-filter"), "");
        return;
      }

      if (e.target.closest && e.target.closest(".qd-picker-confirm")) {
        if (confirmBtn.disabled) return;
        var ids = [];
        for (var k in selected) if (selected[k]) ids.push(k);
        // close(false) — do NOT restore focus to the trigger here. On
        // Read the trigger is a per-verse .trans-open-btn living inside
        // #verseContainer, and onConfirm dispatches the event that
        // re-renders that container: focus would be restored onto a node
        // that is detached microseconds later, dropping the reader to
        // <body> at the top of the document. Re-target afterwards to
        // whatever survived the render instead.
        var trigger = opts.trigger;
        close(false);
        if (opts.onConfirm) opts.onConfirm(ids);
        restoreFocusAfterConfirm(trigger);
        return;
      }
      if (e.target.closest && e.target.closest(".qd-picker-close")) close();
    });

    overlay.addEventListener("change", function (e) {
      var cb = e.target.closest && e.target.closest("[data-item]");
      if (!cb) return;
      var id = cb.getAttribute("data-item");
      if (!multi) {
        selected = {};
        overlay.querySelectorAll("[data-item]").forEach(function (other) {
          other.checked = other === cb;
        });
      }
      selected[id] = cb.checked;
      paintFoot();
    });

    qInput.addEventListener("input", function () {
      var on = overlay.querySelector(".qd-chip.is-on");
      var f = on ? on.getAttribute("data-filter") : "all";
      renderList(f, qInput.value.trim());
    });

    var onKey = makeKeyHandler(dialog);
    document.addEventListener("keydown", onKey, true);

    openState = { overlay: overlay, trigger: opts.trigger || null, onKey: onKey };
    renderList("all", "");
    paintFoot();
    var closeBtn = overlay.querySelector(".qd-picker-close");
    if (closeBtn) closeBtn.focus();
  }

  window.qdPicker = { open: open, openList: openList, close: close, clampRange: clampRange, refLabel: refLabel };
  window.qdRange = { create: createRange };
})();
